"""Sprint 1 smoke test: verify a local VLM accepts and correctly reads images.

Sends the deterministic test frames (generated by scripts/make_test_image.ps1)
to a local Ollama runtime and checks the answers against known image content.
Stdlib only — no project dependencies required.

Examples:
    python scripts/vlm_smoke_test.py                        # single-image test
    python scripts/vlm_smoke_test.py --mode multi           # two-image ordering test
    python scripts/vlm_smoke_test.py --model qwen2.5vl:3b --url http://127.0.0.1:11434
"""

from __future__ import annotations

import argparse
import base64
import json
import sys
import time
import urllib.request
from pathlib import Path

DEFAULT_URL = "http://127.0.0.1:11434"
# Chosen in Sprint 1 (see docs/runtime-feasibility.md): best vision-path speed
# on the 4 GB AMD GPU. qwen2.5vl:3b also passes but encodes ~5-10x slower.
DEFAULT_MODEL = "qwen3.5:4b"
IMAGE_A = Path(__file__).parent.parent / "data" / "cache" / "test_frame_42.png"
IMAGE_B = Path(__file__).parent.parent / "data" / "cache" / "test_frame_B_77.png"

SINGLE_PROMPT = (
    "Look at this image carefully. Answer in three short numbered lines: "
    "1. What exact text is written? "
    "2. What shape is in the bottom-right corner and what color is it? "
    "3. What shape is in the bottom-left corner and what color is it?"
)

MULTI_PROMPT = (
    "You are given two images in order. Answer in two short numbered lines: "
    "1. What exact text is written in the FIRST image? "
    "2. What exact text is written in the SECOND image?"
)


def encode_image(path: Path) -> str:
    return base64.b64encode(path.read_bytes()).decode("ascii")


def chat(url: str, model: str, prompt: str, images: list[str], think: bool) -> dict:
    def post(payload: dict) -> dict:
        req = urllib.request.Request(
            url.rstrip("/") + "/api/chat",
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=300) as resp:
            return json.loads(resp.read().decode("utf-8"))

    message = {"role": "user", "content": prompt, "images": images}
    started = time.perf_counter()
    try:
        result = post({"model": model, "messages": [message], "stream": False, "think": think})
    except urllib.error.HTTPError as exc:
        if exc.code != 400 or not think:  # non-thinking models reject `think`
            raise
        result = post({"model": model, "messages": [message], "stream": False})
    result["_wall_seconds"] = time.perf_counter() - started
    return result


def report(label: str, checks: list[tuple[str, bool]]) -> bool:
    print(f"\n--- {label} ---")
    ok = True
    for name, passed in checks:
        print(f"  [{'PASS' if passed else 'FAIL'}] {name}")
        ok = ok and passed
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default=DEFAULT_URL)
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--mode", choices=["single", "multi"], default="single")
    parser.add_argument(
        "--no-think",
        action="store_true",
        help="Disable thinking mode (faster, but answers may skip parts of "
        "multi-part questions; the correctness gate defaults to thinking on).",
    )
    args = parser.parse_args()

    all_ok = True

    if args.mode == "single":
        if not IMAGE_A.exists():
            print(f"Missing test image: {IMAGE_A}", file=sys.stderr)
            print("Run: powershell -File scripts/make_test_image.ps1", file=sys.stderr)
            return 2
        print(f"Model: {args.model}\nImage: {IMAGE_A.name} ({IMAGE_A.stat().st_size} bytes)")
        result = chat(args.url, args.model, SINGLE_PROMPT, [encode_image(IMAGE_A)], think=not args.no_think)
        answer = result["message"]["content"]
        print(f"\nAnswer:\n{answer}")
        print(
            f"\nWall time: {result['_wall_seconds']:.1f}s"
            + (
                f" | eval: {result.get('eval_count', '?')} tok in "
                f"{result.get('eval_duration', 0) / 1e9:.2f}s "
                f"({result.get('eval_count', 0) / max(result.get('eval_duration', 1), 1) * 1e9:.1f} tok/s)"
                if result.get("eval_duration")
                else ""
            )
        )
        low = answer.lower()
        all_ok = report(
            "Single-image checks",
            [
                ("text 'HELLO 42' read correctly", "hello 42" in low),
                ("red circle identified (bottom-right)", "red" in low and "circle" in low),
                ("green rectangle identified (bottom-left)", "green" in low and "rectangle" in low),
            ],
        )
    else:
        for image in (IMAGE_A, IMAGE_B):
            if not image.exists():
                print(f"Missing test image: {image}", file=sys.stderr)
                return 2
        print(
            f"Model: {args.model}\nImages: {IMAGE_A.name}, {IMAGE_B.name} "
            "(ordering test: A says HELLO 42, B says SECOND 77)"
        )
        result = chat(
            args.url,
            args.model,
            MULTI_PROMPT,
            [encode_image(IMAGE_A), encode_image(IMAGE_B)],
            think=not args.no_think,
        )
        answer = result["message"]["content"]
        print(f"\nAnswer:\n{answer}")
        print(f"\nWall time: {result['_wall_seconds']:.1f}s")
        low = answer.lower()
        # Ordering check is format-agnostic: both strings present, A's position before B's.
        first_ok = "hello 42" in low and "second 77" in low and low.index("hello 42") < low.index("second 77")
        second_ok = "second 77" in low
        all_ok = report(
            "Multi-image checks",
            [
                ("first image text is 'HELLO 42'", first_ok),
                ("second image text is 'SECOND 77'", second_ok),
            ],
        )

    print(f"\nRESULT: {'PASS' if all_ok else 'FAIL'}")
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
